import type { ExportFailureCode, ExportOrchestrator } from './orchestrator.ts';
import type { ContributorSummary } from './schemas.ts';

/**
 * Online export jobs (`_db.md`, `export_jobs`; `_techspec.md`, Export Flow). The job row is safe
 * metadata; package bytes live only in a `TemporaryPackageStore` for a short delivery window,
 * scoped to the requesting user, and are dropped on delivery or expiry.
 */

export type ExportJobState = 'requested' | 'running' | 'completed' | 'failed';

export interface ExportJob {
  readonly id: string;
  readonly campaignId: string;
  readonly requestedBy: string;
  readonly state: ExportJobState;
  /** Lowercase hex SHA-256 of `manifest.json`; completion evidence. */
  readonly manifestChecksum?: string;
  readonly contributorSummary: readonly ContributorSummary[];
  readonly errorCode?: ExportFailureCode | 'export_failed';
  readonly createdAt: Date;
  readonly completedAt?: Date;
}

export const EXPORT_JOB_RETENTION_DAYS = 30;
/** How long generated bytes wait for the requesting user's download. */
export const EXPORT_FILE_TTL_MS = 10 * 60 * 1000;

export interface ExportJobRepository {
  /** Inserts a `requested` job; returns the existing row unchanged when the id already exists. */
  create(input: {
    readonly id: string;
    readonly campaignId: string;
    readonly requestedBy: string;
  }): Promise<{ readonly job: ExportJob; readonly created: boolean }>;
  markRunning(id: string): Promise<void>;
  complete(
    id: string,
    result: { readonly manifestChecksum: string; readonly summary: readonly ContributorSummary[] },
  ): Promise<void>;
  fail(id: string, errorCode: ExportJob['errorCode']): Promise<void>;
  get(id: string): Promise<ExportJob | undefined>;
  /** Campaigns with a `requested` or `running` export: feature 05 retention holds their files. */
  activeCampaignIds(campaignIds: readonly string[]): Promise<ReadonlySet<string>>;
  /** Hard-deletes jobs older than the retention window (database time, exclusive). */
  deleteExpired(): Promise<number>;
}

export class MemoryExportJobRepository implements ExportJobRepository {
  readonly jobs = new Map<string, ExportJob>();

  constructor(private readonly now: () => Date = () => new Date()) {}

  async create(input: { id: string; campaignId: string; requestedBy: string }) {
    const existing = this.jobs.get(input.id);
    if (existing !== undefined) return { job: existing, created: false };
    const job: ExportJob = {
      ...input,
      state: 'requested',
      contributorSummary: [],
      createdAt: this.now(),
    };
    this.jobs.set(job.id, job);
    return { job, created: true };
  }

  async markRunning(id: string) {
    this.#update(id, { state: 'running' });
  }

  async complete(
    id: string,
    result: { manifestChecksum: string; summary: readonly ContributorSummary[] },
  ) {
    this.#update(id, {
      state: 'completed',
      manifestChecksum: result.manifestChecksum,
      contributorSummary: [...result.summary],
      completedAt: this.now(),
    });
  }

  async fail(id: string, errorCode: ExportJob['errorCode']) {
    this.#update(id, { state: 'failed', errorCode, completedAt: this.now() });
  }

  async get(id: string) {
    return this.jobs.get(id);
  }

  async activeCampaignIds(campaignIds: readonly string[]) {
    const wanted = new Set(campaignIds);
    return new Set(
      [...this.jobs.values()]
        .filter(
          (job) =>
            (job.state === 'requested' || job.state === 'running') && wanted.has(job.campaignId),
        )
        .map((job) => job.campaignId),
    );
  }

  async deleteExpired() {
    const cutoff = this.now().getTime() - EXPORT_JOB_RETENTION_DAYS * 86_400_000;
    let deleted = 0;
    for (const [id, job] of this.jobs) {
      if (job.createdAt.getTime() < cutoff) {
        this.jobs.delete(id);
        deleted += 1;
      }
    }
    return deleted;
  }

  #update(id: string, patch: Partial<ExportJob>) {
    const job = this.jobs.get(id);
    if (job !== undefined) this.jobs.set(id, { ...job, ...patch });
  }
}

interface HeldPackage {
  readonly userId: string;
  readonly parts: readonly Uint8Array[];
  readonly size: number;
  readonly expiresAt: number;
}

/**
 * Process-local holding area for generated packages. Never persisted and never in campaign object
 * storage; an entry is reachable only by its job id and requesting user, and disappears on
 * `release`, on expiry, or when the process stops.
 */
export class TemporaryPackageStore {
  readonly #held = new Map<string, HeldPackage>();

  constructor(
    private readonly ttlMs: number = EXPORT_FILE_TTL_MS,
    private readonly now: () => number = () => Date.now(),
  ) {}

  put(jobId: string, userId: string, parts: readonly Uint8Array[]): Date {
    this.sweep();
    const expiresAt = this.now() + this.ttlMs;
    const size = parts.reduce((sum, part) => sum + part.length, 0);
    this.#held.set(jobId, { userId, parts, size, expiresAt });
    return new Date(expiresAt);
  }

  get(
    jobId: string,
    userId: string,
  ):
    | { readonly parts: readonly Uint8Array[]; readonly size: number; readonly expiresAt: Date }
    | undefined {
    this.sweep();
    const held = this.#held.get(jobId);
    if (held === undefined || held.userId !== userId) return undefined;
    return { parts: held.parts, size: held.size, expiresAt: new Date(held.expiresAt) };
  }

  expiresAt(jobId: string, userId: string): Date | undefined {
    return this.get(jobId, userId)?.expiresAt;
  }

  release(jobId: string): void {
    this.#held.delete(jobId);
  }

  /** Drops expired entries; returns how many were dropped. */
  sweep(): number {
    const now = this.now();
    let dropped = 0;
    for (const [jobId, held] of this.#held) {
      if (held.expiresAt <= now) {
        this.#held.delete(jobId);
        dropped += 1;
      }
    }
    return dropped;
  }

  get heldCount(): number {
    return this.#held.size;
  }

  startSweeping(intervalMs = 60_000): () => void {
    const timer = setInterval(() => this.sweep(), intervalMs);
    (timer as { unref?: () => void }).unref?.();
    return () => clearInterval(timer);
  }
}

export interface ExportJobView {
  readonly jobId: string;
  readonly campaignId: string;
  readonly state: ExportJobState;
  readonly summary: ContributorSummary[];
  readonly errorCode?: string;
  readonly createdAt: string;
  readonly completedAt?: string;
  /** Present while the requesting user can still download the file. */
  readonly fileAvailableUntil?: string;
}

export type StartExportError = 'job_conflict';

/**
 * Runs one online export as a job. The caller has already authorized the Actor (current `owner`
 * or `gm` through feature 04) for `campaignId`; this service enforces job ownership.
 */
export class OnlineExportService {
  constructor(
    private readonly deps: {
      readonly jobs: ExportJobRepository;
      readonly orchestrator: Pick<ExportOrchestrator, 'export'>;
      readonly files: TemporaryPackageStore;
      /** Failure codes only; never payload, path or package content. */
      readonly log?: { exportFailed(code: string, moduleId?: string): void };
    },
  ) {}

  /**
   * Idempotent per job id: a retried request with the same id returns that job as it stands and
   * never generates twice. A job id that belongs to another user or campaign is a conflict.
   */
  async start(input: {
    readonly jobId: string;
    readonly campaignId: string;
    readonly userId: string;
    readonly displayName: string;
  }): Promise<{ ok: true; value: ExportJobView } | { ok: false; error: StartExportError }> {
    const { job, created } = await this.deps.jobs.create({
      id: input.jobId,
      campaignId: input.campaignId,
      requestedBy: input.userId,
    });
    if (job.requestedBy !== input.userId || job.campaignId !== input.campaignId) {
      return { ok: false, error: 'job_conflict' };
    }
    if (!created) return { ok: true, value: this.#view(job) };

    await this.deps.jobs.markRunning(job.id);
    let failure: ExportJob['errorCode'] | undefined;
    try {
      const result = await this.deps.orchestrator.export(input.campaignId, {
        exportedBy: { displayName: input.displayName },
      });
      if (result.ok) {
        this.deps.files.put(job.id, input.userId, result.value.parts);
        await this.deps.jobs.complete(job.id, {
          manifestChecksum: result.value.manifestChecksum,
          summary: result.value.summary,
        });
      } else {
        failure = result.error.code;
        this.deps.log?.exportFailed(result.error.code, result.error.moduleId);
      }
    } catch {
      failure = 'export_failed';
      this.deps.log?.exportFailed('export_failed');
    }
    if (failure !== undefined) {
      this.deps.files.release(job.id);
      await this.deps.jobs.fail(job.id, failure);
    }
    const settled = (await this.deps.jobs.get(job.id)) ?? job;
    return { ok: true, value: this.#view(settled) };
  }

  /** The job, only for its requesting user. */
  async status(jobId: string, userId: string): Promise<ExportJobView | undefined> {
    const job = await this.deps.jobs.get(jobId);
    return job === undefined || job.requestedBy !== userId ? undefined : this.#view(job);
  }

  async job(jobId: string): Promise<ExportJob | undefined> {
    return this.deps.jobs.get(jobId);
  }

  /** The package bytes, only for the requesting user and only inside the delivery window. */
  file(jobId: string, userId: string) {
    return this.deps.files.get(jobId, userId);
  }

  /** Called once the file was delivered in full: the bytes leave the server. */
  delivered(jobId: string): void {
    this.deps.files.release(jobId);
  }

  #view(job: ExportJob): ExportJobView {
    const until =
      job.state === 'completed' ? this.deps.files.expiresAt(job.id, job.requestedBy) : undefined;
    return {
      jobId: job.id,
      campaignId: job.campaignId,
      state: job.state,
      summary: [...job.contributorSummary],
      ...(job.errorCode === undefined ? {} : { errorCode: job.errorCode }),
      createdAt: job.createdAt.toISOString(),
      ...(job.completedAt === undefined ? {} : { completedAt: job.completedAt.toISOString() }),
      ...(until === undefined ? {} : { fileAvailableUntil: until.toISOString() }),
    };
  }
}
